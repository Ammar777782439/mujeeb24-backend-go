package ports

import (
	"context"
	"time"
)

// InboundMediaSource is a short-lived provider URL resolved just in time for
// ingestion. The URL must never be persisted as a canonical media reference.
type InboundMediaSource struct {
	// URL is used for platform-hosted media. ProviderMediaID is used when
	// SocialAPI must proxy the download (WhatsApp and Telegram).
	URL             string
	ProviderMediaID string
	Kind            string
}

// InboundMediaSourceResolver resolves an opaque webhook reference through the
// provider's authenticated conversation API. Implementations must not expose
// provider SDK types or persist the resolved URL.
type InboundMediaSourceResolver interface {
	ResolveInboundMediaSource(ctx context.Context, providerConversationID, providerMediaReference, expectedKind string) (InboundMediaSource, error)
}

type InboundMediaDownloader interface {
	// maxBytes is mandatory and must be enforced while reading the response.
	DownloadInboundMedia(ctx context.Context, providerMediaID string, maxBytes int64) ([]byte, string, error)
}

// PendingConversationMediaAsset is a tenant-owned placeholder created before
// provider media retrieval. The storage key is generated by Mujeeb and contains
// no provider URL, filename, or user-controlled path segment.
type PendingConversationMediaAsset struct {
	ID              string
	BusinessID      string
	StorageProvider string
	StorageKey      string
	Kind            string
	CreatedBy       *string
}

// ConversationMediaIngestionRepository owns lifecycle changes for media
// ingested from a provider. Object-storage/network I/O is never performed by
// this repository.
type ConversationMediaIngestionRepository interface {
	CreatePendingIngestion(ctx context.Context, draft PendingConversationMediaAsset) (MediaAsset, error)
	GetAsset(ctx context.Context, businessID, mediaAssetID string) (MediaAsset, error)
	MarkImageReady(ctx context.Context, businessID, mediaAssetID string, verified VerifiedImage) (MediaAsset, error)
	MarkIngestionRejected(ctx context.Context, businessID, mediaAssetID string) (MediaAsset, error)
}

// MessageAttachmentDraft links one Mujeeb-owned MediaAsset to one
// communication message. A pending ingestion requires an opaque provider
// media reference; that reference is internal and is never exposed in message
// DTOs or logs.
type MessageAttachmentDraft struct {
	ID                     string
	BusinessID             string
	CommunicationMessageID string
	MediaAssetID           string
	Kind                   string
	Caption                string
	SortOrder              int
	SourceProviderMediaRef *string
	CreatedAt              time.Time
}

// MessageAttachmentRecord is a read model for an attachment relation. Storage
// keys and provider references are intentionally omitted from normal message
// projections; a dedicated ingestion worker may load the source reference
// through a separately authorized internal query in a later slice.
type MessageAttachmentRecord struct {
	ID                     string
	BusinessID             string
	CommunicationMessageID string
	MediaAssetID           string
	Kind                   string
	MimeType               string
	Caption                string
	Status                 string
	SortOrder              int
	SizeBytes              int64
	CreatedAt              time.Time
	UpdatedAt              time.Time
}

type ClaimedMessageAttachmentIngestion struct {
	AttachmentID            string
	BusinessID              string
	CommunicationMessageID  string
	MediaAssetID             string
	ProviderConversationID  string
	ProviderMediaReference  string
	Kind                    string
	StorageProvider         string
	StorageKey              string
	AttemptCount            int
}

type MessageAttachmentRepository interface {
	Create(ctx context.Context, draft MessageAttachmentDraft) (MessageAttachmentRecord, error)
	ListByMessage(ctx context.Context, businessID, communicationMessageID string) ([]MessageAttachmentRecord, error)
	ClaimPendingIngestions(ctx context.Context, limit int, lease time.Duration) ([]ClaimedMessageAttachmentIngestion, error)
	ReleaseForRetry(ctx context.Context, businessID, attachmentID string, nextAttemptAt time.Time, errorCode string) error
	MarkReady(ctx context.Context, businessID, attachmentID string) (MessageAttachmentRecord, error)
	MarkFailed(ctx context.Context, businessID, attachmentID string) (MessageAttachmentRecord, error)
}
